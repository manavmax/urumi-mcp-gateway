import { useState } from "react";
import { useNavigate } from "react-router-dom";
import { useAuth } from "../lib/auth";

export default function Login() {
  const { login } = useAuth();
  const nav = useNavigate();
  const [email, setEmail] = useState("admin@urumi.local");
  const [password, setPassword] = useState("");
  const [err, setErr] = useState("");
  const [busy, setBusy] = useState(false);

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    setErr("");
    if (!email.trim() || !password) {
      setErr("Enter email and password.");
      return;
    }
    setBusy(true);
    try {
      await login(email.trim(), password);
      nav("/", { replace: true });
    } catch (e: unknown) {
      setErr(e instanceof Error ? e.message : String(e));
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="center">
      <form onSubmit={submit} className="card login-card" aria-label="Sign in">
        <div className="kicker">Urumi Gateway</div>
        <h1 style={{ margin: 0, fontSize: 22 }}>Sign in</h1>
        <p className="small muted" style={{ margin: 0 }}>
          The administrator password is generated by the Helm chart and lives only in the <code className="mono small">gateway-admin</code> Secret. Read it with <code className="mono small">make gateway-admin-password</code>.
        </p>
        {err && <div className="alert alert-error" role="alert">{err}</div>}
        <label>
          <span>Email</span>
          <input value={email} onChange={(e) => setEmail(e.target.value)} autoComplete="username" placeholder="admin@urumi.local" />
        </label>
        <label>
          <span>Password</span>
          <input type="password" value={password} onChange={(e) => setPassword(e.target.value)} autoComplete="current-password" placeholder="••••••••" />
        </label>
        <button type="submit" disabled={busy} style={{ marginTop: 4 }}>
          {busy ? "Signing in…" : "Sign in"}
        </button>
      </form>
    </div>
  );
}
